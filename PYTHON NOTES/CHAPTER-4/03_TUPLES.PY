# --NOTE: TUPLES ARE IMMUTABLE, I.E, ONCE CREATED, THEIR ELEMENTS CANNOT BE CHANGED.

c = (1, 2, 3, 4, 5)
# c[0] = 10  # This will raise an error because tuples are immutable
print(c)  # Output: (1, 2, 3, 4, 5)

# To modify a tuple, you need to convert it to a list {iss ()>[]isme change krdo}, make changes, and 
# then convert it back to a tuple.



#-----------------------------------CONVERTING TUPLE TO LIST AND BACK TO TUPLE----------------------------------


c = (1, 2, 3, 4, 5)

temp_list = list(c)  # Convert tuple to list
temp_list[0] = 10  # Modify the list
c = tuple(temp_list)  # Convert list back to tuple
print(c)  # Output: (10, 2, 3, 4, 5)



#-----------------------------------------------x-----------------------------------------------------------



#-----------------------------------TUPLE UNPACKING---------------------------------------------------------

d = (1, 2, 3)
x, y, z = d  # Unpacking the tuple into variables
print(x)  # Output: 1
print(y)  # Output: 2
print(z)  # Output: 3

#-----------------------------------------------x-----------------------------------------------------------



#-----------------------------------NESTED TUPLES----------------------------------------------------------

nested_tuple = (1, 2, (3, 4), 5)
print(nested_tuple[2])        # Output: (3, 4)
print(nested_tuple[2][0])     # Output: 3
print(nested_tuple[2][1])     # Output: 4


#-----------------------------------------------x-----------------------------------------------------------




#-----------------------------------TUPLE METHODS----------------------------------------------------------

e = (1, 2, 3, 2, 4, 2)
print(e.count(2))  # Output: 3 (counts how many times 2 appears in the tuple)
print(e.index(3))  # Output: 2 (finds the index of the first occurrence of 3)


#-----------------------------------------------x-----------------------------------------------------------



#-----------------------------------TUPLE IMMUTABILITY DEMONSTRATION---------------------------------------

f = (1, 2, 3)
try:
    f[0] = 10  # Attempting to change the first element
except TypeError as e:
    print(e)  # Output: 'tuple' object does not support item assignment


#-----------------------------------------------x-----------------------------------------------------------



#-----------------------------------TUPLE WITH MIXED DATA TYPES--------------------------------------------

mixed_tuple = (1, "Hello", 3.14, True)
print(mixed_tuple)  # Output: (1, 'Hello', 3.14


#-----------------------------------------------x-----------------------------------------------------------



#-----------------------------------TUPLE SLICING---------------------------------------------------------

g = (0, 1, 2, 3, 4, 5)
print(g[1:4])  # Output: (1, 2, 3)
print(g[:3])   # Output: (0, 1, 2)
print(g[3:])   # Output: (3, 4, 5)
print(g[-3:])  # Output: (3, 4, 5)
print(g[:-3])  # Output: (0, 1, 2)


#-----------------------------------------------x-----------------------------------------------------------



#-----------------------------------TUPLE CONCATENATION AND REPLICATION------------------------------------

h = (1, 2, 3)
i = (4, 5, 6)
j = h + i  # Concatenation
print(j)  # Output: (1, 2, 3, 4, 5, 6)

k = h * 2  # Replication
print(k)  # Output: (1, 2, 3, 1, 2, 3)


#-----------------------------------------------x-----------------------------------------------------------



#-----------------------------------TUPLE LENGTH----------------------------------------------------------

l = (1, 2, 3, 4, 5)
print(len(l))  # Output: 5

#-----------------------------------------------x-----------------------------------------------------------



#-----------------------------------TUPLE MEMBERSHIP TESTING-------------------------------------------

m = (1, 2, 3, 4, 5)
print(3 in m)   # Output: True
print(6 not in m)  # Output: True

#-----------------------------------------------x-----------------------------------------------------------



