#--- Using Escape Sequence to include double quotes in string ---

b = "Bittu is a good \"boy\" "  # Using escape sequence to include double quotes

print(b)

#--- Using Escape Sequence to include single quotes in string ---

c = 'Bittu is a good \'boy\' '  # Using escape sequence to include single quotes

print(c)

#--- Using Escape Sequence to include backslash in string ---

d = "This is a backslash: \\ "  # Using escape sequence to include backslash

print(d)

#--- Using Escape Sequence for tab space in string ---

e = "Bittu\tis\ta\tgood\tboy"  # Using escape sequence for tab space

print(e)

#--- Using Escape Sequence for carriage return in string ---

f = "Bittu is a good boy\rHe loves gaming"  # Using escape sequence for carriage return

print(f)

#--- Using Escape Sequence for backspace in string ---

g = "Bittu is a good boy\b"  # Using escape sequence for backspace

print(g)

#--- Using Escape Sequence for form feed in string ---

h = "Bittu is a good boy \f He loves coding"  # Using escape sequence for form feed

print(h)

#--- Using Escape Sequence for vertical tab in string ---

i = "Bittu is a good boy \v He loves gaming"  # Using escape sequence for vertical tab

print(i)

#--- Using Escape Sequence for Unicode character in string ---

j = "Bittu loves the symbol \u2764"  # Using escape sequence for Unicode character

print(j)

#--- Using Escape Sequence for octal value in string ---

k = "Bittu loves the symbol \101"  # Using escape sequence for octal value

print(k)

#--- Using Escape Sequence for hexadecimal value in string ---

l = "Bittu loves the symbol \x41"  # Using escape sequence for hexadecimal value

print(l)

#--- Using Escape Sequence for raw string ---

m = r"Bittu is a good boy \n He loves gaming"  # Using raw string to ignore escape sequences

print(m)

